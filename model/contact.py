class Contact:
    def __init__(self, firstname=None, middlename=None, lastname=None,
                 nickname=None, address=None, home=None, mobile=None,
                 work=None, email=None, email2=None, email3=None):
        self.firstname = firstname
        self.middlename = middlename
        self.lastname = lastname
        self.nickname = nickname
        self.address = address
        self.home = home
        self.mobile = mobile
        self.work = work
        self.email = email
        self.email2 = email2
        self.email3 = email3